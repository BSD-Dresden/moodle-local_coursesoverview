class observer {
    /**
     * Let an order forget its course once the course is gone.
     *
     * Listening to the event rather than to our own delete page covers every
     * way a course can disappear, including the course management pages. The
     * order itself stays: it still says who ordered what and when.
     *
     * @param \core\event\course_deleted $event
     */
    public static function course_deleted(\core\event\course_deleted $event): void {
        global $DB;

        $DB->set_field('local_coursesoverview_order', 'courseid', null, ['courseid' => $event->objectid]);
    }
}
